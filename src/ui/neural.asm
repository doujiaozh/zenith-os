; -----------------------------------------------------------------------------
; ui_build_clock: "T+MM:SS"
; -----------------------------------------------------------------------------
ui_build_clock:
    pushad
    mov edi, ui_buf_clock
    mov byte [edi], 'T'
    mov byte [edi + 1], '+'
    mov eax, [ui_minute]
    lea edi, [ui_buf_clock + 2]
    mov ecx, 2
    call u32_to_dec_pad
    mov byte [ui_buf_clock + 4], ':'
    mov eax, [ui_second]
    lea edi, [ui_buf_clock + 5]
    mov ecx, 2
    call u32_to_dec_pad
    mov byte [ui_buf_clock + 7], 0
    popad
    ret

; -----------------------------------------------------------------------------
; ui_build_fps: "FPS <n>  AI <spikes>/s"
; -----------------------------------------------------------------------------
ui_build_fps:
    pushad
    mov edi, ui_buf_fps
    mov esi, str_fps
    call ui_append_str
    mov eax, [ui_fps]
    call ui_append_u32
    mov esi, str_ai
    call ui_append_str
    mov eax, [ui_spike_rate]
    call ui_append_u32
    mov esi, str_per_s
    call ui_append_str
    mov byte [edi], 0
    popad
    ret

; -----------------------------------------------------------------------------
; ui_build_status: PMM / heap / selftest telemetry
; -----------------------------------------------------------------------------
ui_build_status:
    pushad
    mov edi, ui_buf_status
    mov esi, str_pmm
    call ui_append_str
    mov eax, [pmm_free_pages]
    shl eax, 2
    shr eax, 10                    ; MiB
    call ui_append_u32
    mov esi, str_mb_free
    call ui_append_str
    mov esi, str_heap
    call ui_append_str
    call heap_free_bytes
    shr eax, 10                    ; KiB
    call ui_append_u32
    mov esi, str_k
    call ui_append_str
    mov esi, str_selftest
    call ui_append_str
    mov eax, [selftest_passed]
    call ui_append_u32
    mov esi, ui_slash
    call ui_append_str
    mov eax, [selftest_total]
    call ui_append_u32
    mov byte [edi], 0
    popad
    ret

; -----------------------------------------------------------------------------
; ui_build_rtc: "HH:MM:SS"
; -----------------------------------------------------------------------------
ui_build_rtc:
    pushad
    movzx eax, byte [rtc_hour]
    mov edi, ui_buf_rtc
    mov ecx, 2
    call u32_to_dec_pad
    mov byte [ui_buf_rtc + 2], ':'
    movzx eax, byte [rtc_minute]
    lea edi, [ui_buf_rtc + 3]
    mov ecx, 2
    call u32_to_dec_pad
    mov byte [ui_buf_rtc + 5], ':'
    movzx eax, byte [rtc_second]
    lea edi, [ui_buf_rtc + 6]
    mov ecx, 2
    call u32_to_dec_pad
    mov byte [ui_buf_rtc + 8], 0
    popad
    ret

; -----------------------------------------------------------------------------
; ui_append_str: ESI = source, EDI = destination; appends NUL-terminated text
; -----------------------------------------------------------------------------
ui_append_str:
    push eax
.loop:
    lodsb
    test al, al
    jz .done
    mov [edi], al
    inc edi
    jmp .loop
.done:
    pop eax
    ret

; -----------------------------------------------------------------------------
; ui_append_u32: EAX = value, EDI = destination; appends decimal digits
; -----------------------------------------------------------------------------
ui_append_u32:
    push edi
    mov edi, ui_tmp_num
    call u32_to_dec
    mov esi, ui_tmp_num
    pop edi
    call ui_append_str
    ret

; -----------------------------------------------------------------------------
; ui_draw_text_right: EAX = right edge, EBX = y, ESI = string, EDX = colour
; -----------------------------------------------------------------------------
ui_draw_text_right:
    push eax
    push ebx
    push edx
    push esi
    call str_len
    imul eax, eax, 6
    pop esi
    pop edx
    pop ebx
    pop ecx
    sub ecx, eax
    mov eax, ecx
    call vga_draw_text
    ret

