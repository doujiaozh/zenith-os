; =============================================================================
;  ZenithOS - ui/neural.asm
;  The default desktop: a 3D neon neural mesh rendered entirely in assembly on
;  a 320x200x256 VGA back buffer.
;
;  Pipeline per frame (paced by the 100 Hz PIT):
;    input -> SNN inference -> camera transform -> perspective projection ->
;    depth sort -> background grid + starfield -> synapse edges -> travelling
;    data packets -> neuron glow -> cyberpunk HUD -> VGA present
;
;  Camera (WASD):
;    W / S      dolly in / out          A / D      yaw
;    Q / E      pitch up / down         R          reset camera
;    C          toggle cinematic auto-rotation    SPACE  boost rotation speed
;    arrow keys mirror zoom/yaw
;
;  Coordinate system: model coordinates are Q8.8 fixed point (1 px = 256).
;  Angles are 16-bit binary radians; sin/cos come from the 256-entry Q8.8
;  table generated by build.js (lib/fixed.asm).  Projection is
;        screen = centre + (axis * FOV) / depth
;  which keeps the whole 3D path integer-only and deterministic.
; =============================================================================

[bits 32]

