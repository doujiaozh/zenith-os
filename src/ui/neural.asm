UI_FOV          equ 260         ; projection focal length (pixels)
UI_ZOOM_MIN     equ 130
UI_ZOOM_MAX     equ 560
UI_STARS        equ 72
UI_PACKETS      equ 12

; =============================================================================
;  Init
; =============================================================================
ui_init:
    mov dword [ui_last_tick], 0
    mov dword [ui_frames], 0
    mov dword [ui_fps], 0
    mov dword [ui_last_sec], 0
    mov dword [ui_spike_last], 0
    mov dword [ui_spike_rate], 0
    mov dword [ui_zoom], 240
    mov word [ui_yaw], 0
    mov word [ui_pitch], 0
    mov dword [ui_auto], 1
    call ui_build_model
    call ui_build_stars
    ret

; =============================================================================
;  Frame loop
; =============================================================================
ui_frame:
    call ui_input
    call ui_update_stats
    call ui_ai_step
    call ui_project
    call ui_sort_nodes
    call ui_draw_background
    call ui_draw_stars
    call ui_draw_grid
    call ui_draw_edges
    call ui_draw_packets
    call ui_draw_nodes
    call ui_draw_hud
    call vga_present
    call ui_wait_tick
    ret

; =============================================================================
;  Input
; =============================================================================
ui_input:
    pushad
    mov eax, [kbd_held_mask]
    mov [ui_held], eax

    ; Rotation speed (SPACE boosts).
    mov ecx, 96
    test eax, 1 << KEY_SPACE
    jz .speed_ok
    imul ecx, ecx, 3
.speed_ok:

    ; A / D yaw
    bt eax, KEY_A
    jnc .no_a
    sub word [ui_yaw], cx
    mov dword [ui_auto], 0
.no_a:
    mov eax, [ui_held]
    bt eax, KEY_D
    jnc .no_d
    add word [ui_yaw], cx
    mov dword [ui_auto], 0
.no_d:
    mov eax, [ui_held]
    bt eax, KEY_LEFT
    jnc .no_left
    sub word [ui_yaw], cx
    mov dword [ui_auto], 0
.no_left:
    mov eax, [ui_held]
    bt eax, KEY_RIGHT
    jnc .no_right
    add word [ui_yaw], cx
    mov dword [ui_auto], 0
.no_right:

    ; Q / E pitch (clamped to +/- 6000, roughly +/- 33 degrees)
    mov ecx, 64
    mov eax, [ui_held]
    bt eax, KEY_SPACE
    jnc .pitch_speed_ok
    imul ecx, ecx, 2
.pitch_speed_ok:
    mov eax, [ui_held]
    bt eax, KEY_Q
    jnc .no_q
    movsx eax, word [ui_pitch]
    add eax, ecx
    cmp eax, 6000
    jle .q_store
    mov eax, 6000
    jmp .q_store
.no_q:
    mov eax, [ui_held]
    bt eax, KEY_E
    jnc .no_pitch_store
    movsx eax, word [ui_pitch]
    sub eax, ecx
    cmp eax, -6000
    jge .q_store
    mov eax, -6000
.q_store:
    ; Only store when Q or E is actually held.
    mov ebx, [ui_held]
    bt ebx, KEY_Q
    jc .pitch_changed
    bt ebx, KEY_E
    jnc .no_pitch_store
.pitch_changed:
    mov [ui_pitch], ax
.no_pitch_store:

    ; W / S / arrows dolly
    mov eax, [ui_held]
    bt eax, KEY_W
    jnc .no_w
    sub dword [ui_zoom], 3
    mov dword [ui_auto], 0
.no_w:
    mov eax, [ui_held]
    bt eax, KEY_S
    jnc .no_s
    add dword [ui_zoom], 3
    mov dword [ui_auto], 0
.no_s:
    mov eax, [ui_held]
    bt eax, KEY_UP
    jnc .no_up
    sub dword [ui_zoom], 3
.no_up:
    mov eax, [ui_held]
    bt eax, KEY_DOWN
    jnc .no_down
    add dword [ui_zoom], 3
.no_down:
    mov eax, [ui_zoom]
    cmp eax, UI_ZOOM_MIN
    jge .zoom_min_ok
    mov eax, UI_ZOOM_MIN
.zoom_min_ok:
    cmp eax, UI_ZOOM_MAX
    jle .zoom_max_ok
    mov eax, UI_ZOOM_MAX
.zoom_max_ok:
    mov [ui_zoom], eax

    ; Cinematic auto-rotation when idle and enabled.
    cmp dword [ui_auto], 0
    je .discrete
    mov eax, [ui_held]
    and eax, 0x0FBF               ; movement keys: W/A/S/D/Q/E/arrows/space
    jnz .discrete
    add word [ui_yaw], 10

.discrete:
    ; Drain discrete key events: R reset, C toggle auto, others stimulate SNN.
.poll:
    call kbd_poll
    test eax, eax
    jz .done
    and eax, 0xFF
    cmp eax, KEY_R
    je .reset
    cmp eax, KEY_C
    je .toggle_auto
    cmp eax, 7
    ja .poll
    call snn_stimulate
    jmp .poll
.reset:
    mov word [ui_yaw], 0
    mov word [ui_pitch], 0
    mov dword [ui_zoom], 240
    mov dword [ui_auto], 1
    jmp .poll
.toggle_auto:
    xor dword [ui_auto], 1
    jmp .poll
.done:
    popad
    ret

; =============================================================================
;  Stats / clock
; =============================================================================
ui_update_stats:
    inc dword [ui_frames]
    mov eax, [pit_ticks]
    mov edx, eax
    sub edx, [ui_last_sec]
    cmp edx, PIT_HZ
    jb .clock_only
    mov eax, [ui_frames]
    mov [ui_fps], eax
    mov dword [ui_frames], 0
    add dword [ui_last_sec], PIT_HZ
    mov eax, [snn_spike_count]
    mov edx, [ui_spike_last]
    sub eax, edx
    mov [ui_spike_rate], eax
    mov eax, [snn_spike_count]
    mov [ui_spike_last], eax
    call rtc_read_time
.clock_only:
    mov eax, [pit_ticks]
    xor edx, edx
    mov ebx, PIT_HZ
    div ebx
    xor edx, edx
    mov ebx, 60
    div ebx
    mov [ui_minute], eax
    mov [ui_second], edx
    ret

; -----------------------------------------------------------------------------
; ui_ai_step: advance the network once per elapsed systick (max 4 catch-up)
; -----------------------------------------------------------------------------
ui_ai_step:
    push eax
    push ecx
    mov eax, [pit_ticks]
    sub eax, [ui_last_tick]
    jz .done
    cmp eax, 4
    jbe .count_ok
    mov eax, 4
.count_ok:
    mov ecx, eax
.step:
    push ecx
    call snn_tick
    pop ecx
    loop .step
    mov eax, [pit_ticks]
    mov [ui_last_tick], eax
.done:
    pop ecx
    pop eax
    ret

; -----------------------------------------------------------------------------
; ui_wait_tick: pace to the next 100 Hz heartbeat
; -----------------------------------------------------------------------------
ui_wait_tick:
    mov eax, [pit_ticks]
.wait:
    cmp eax, [pit_ticks]
    je .wait
    ret

; =============================================================================
;  Model construction: 24 neurons on two rings + 4 axis nodes + 4 core nodes,
;  connected by 40 synapse edges.
; =============================================================================
ui_build_model:
    pushad

    ; --- ring A (0..7) and ring B (8..15) ------------------------------------
    xor ebx, ebx
.ring:
    ; ring A: angle = i*32, y = -42 px
    mov eax, ebx
    shl eax, 5                     ; i * 32
    mov [ui_tmp_angle], eax
    call ui_sphere_point
    imul edi, ebx, 6
    lea edi, [ui_nodes + edi]
    mov eax, [ui_tmp_x]
    mov [edi + 0], ax
    mov word [edi + 2], -10752     ; -42.0
    mov eax, [ui_tmp_z]
    mov [edi + 4], ax

    ; ring B: angle = i*32 + 16, y = +42 px
    mov eax, ebx
    shl eax, 5
    add eax, 16
    mov [ui_tmp_angle], eax
    call ui_sphere_point
    lea edx, [ebx + 8]
    imul edi, edx, 6
    lea edi, [ui_nodes + edi]
    mov eax, [ui_tmp_x]
    mov [edi + 0], ax
    mov word [edi + 2], 10752
    mov eax, [ui_tmp_z]
    mov [edi + 4], ax

    inc ebx
    cmp ebx, 8
    jb .ring

    ; --- axis nodes (16..19): (+-100,0,0) and (0,0,+-100) ---------------------
    lea edi, [ui_nodes + 16 * 6]
    mov word [edi + 0], 25600
    mov word [edi + 2], 0
    mov word [edi + 4], 0
    mov word [edi + 6], -25600
    mov word [edi + 8], 0
    mov word [edi + 10], 0
    mov word [edi + 12], 0
    mov word [edi + 14], 0
    mov word [edi + 16], 25600
    mov word [edi + 18], 0
    mov word [edi + 20], 0
    mov word [edi + 22], -25600

    ; --- core nodes (20..23): tetrahedron at ~35 px --------------------------
    lea edi, [ui_nodes + 20 * 6]
    mov word [edi + 0], 8960
    mov word [edi + 2], 8960
    mov word [edi + 4], 8960
    mov word [edi + 6], -8960
    mov word [edi + 8], -8960
    mov word [edi + 10], 8960
    mov word [edi + 12], 8960
    mov word [edi + 14], -8960
    mov word [edi + 16], -8960
    mov word [edi + 18], -8960
    mov word [edi + 20], 8960
    mov word [edi + 22], -8960

    ; --- edges ---------------------------------------------------------------
    lea edi, [ui_edges]
    xor ebx, ebx
.rings:
    ; A_i -- A_{i+1}
    mov eax, ebx
    mov [edi], al
    lea eax, [ebx + 1]
    and eax, 7
    mov [edi + 1], al
    add edi, 2
    ; B_i -- B_{i+1}
    lea eax, [ebx + 8]
    mov [edi], al
    lea eax, [ebx + 9]
    and eax, 7
    add eax, 8
    mov [edi + 1], al
    add edi, 2
    ; A_i -- B_i
    mov eax, ebx
    mov [edi], al
    lea eax, [ebx + 8]
    mov [edi + 1], al
    add edi, 2
    ; A_i -- B_{i+1}
    mov eax, ebx
    mov [edi], al
    lea eax, [ebx + 1]
    and eax, 7
    add eax, 8
    mov [edi + 1], al
    add edi, 2
    inc ebx
    cmp ebx, 8
    jb .rings

    ; 4 axis -> core links
    xor ebx, ebx
.axis_core:
    lea eax, [ebx + 16]
    mov [edi], al
    lea eax, [ebx + 20]
    mov [edi + 1], al
    add edi, 2
    inc ebx
    cmp ebx, 4
    jb .axis_core

    ; 4 axis -> ring links
    xor ebx, ebx
.axis_ring:
    lea eax, [ebx + 16]
    mov [edi], al
    mov eax, ebx
    shl eax, 1
    mov [edi + 1], al
    add edi, 2
    inc ebx
    cmp ebx, 4
    jb .axis_ring

    popad
    ret

; -----------------------------------------------------------------------------
; ui_sphere_point: angle in ui_tmp_angle -> ui_tmp_x / ui_tmp_z (Q8.8)
; radius = 88 px, using the generated Q8.8 trig table.
; -----------------------------------------------------------------------------
ui_sphere_point:
    push eax
    push edx
    movzx eax, byte [ui_tmp_angle]
    movsx eax, word [trig_cos + eax * 2]
    imul eax, 22528                ; 88 * 256
    sar eax, 8
    mov [ui_tmp_x], eax
    movzx eax, byte [ui_tmp_angle]
    movsx eax, word [trig_sin + eax * 2]
    imul eax, 22528
    sar eax, 8
    mov [ui_tmp_z], eax
    pop edx
    pop eax
    ret

; -----------------------------------------------------------------------------
; ui_build_stars: deterministic starfield via xorshift32
; -----------------------------------------------------------------------------
ui_build_stars:
    pushad
    mov eax, 0xC0FFEE11
    xor ecx, ecx
.loop:
    ; xorshift32
    mov edx, eax
    shl edx, 13
    xor eax, edx
    mov edx, eax
    shr edx, 17
    xor eax, edx
    mov edx, eax
    shl edx, 5
    xor eax, edx

    ; x = (rand & 0xFF) + ((rand >> 8) & 0x3F) -> 0..318
    mov edx, eax
    and edx, 0xFF
    mov ebx, eax
    shr ebx, 8
    and ebx, 0x3F
    add edx, ebx
    mov [ui_star_x + ecx], dl

    ; y = ((rand >> 14) & 0x7F) + ((rand >> 21) & 0x3F) + ((rand >> 27) & 0x07)
    mov edx, eax
    shr edx, 14
    and edx, 0x7F
    mov ebx, eax
    shr ebx, 21
    and ebx, 0x3F
    add edx, ebx
    mov ebx, eax
    shr ebx, 27
    and ebx, 0x07
    add edx, ebx
    mov [ui_star_y + ecx], dl

    ; phase
    mov edx, eax
    shr edx, 5
    and edx, 0x1F
    mov [ui_star_phase + ecx], dl

    inc ecx
    cmp ecx, UI_STARS
    jb .loop
    popad
    ret

; =============================================================================
;  Camera transform + perspective projection
; =============================================================================
ui_project:
    pushad

    ; Camera sin/cos for this frame.
    mov ax, [ui_yaw]
    call fcos
    mov [ui_cosy], eax
    mov ax, [ui_yaw]
    call fsin
    mov [ui_siny], eax
    mov ax, [ui_pitch]
    call fcos
    mov [ui_cosp], eax
    mov ax, [ui_pitch]
    call fsin
    mov [ui_sinp], eax

    mov eax, [ui_zoom]
    shl eax, 8
    mov [ui_zoom_q8], eax

    mov dword [ui_i], 0
.node:
    mov esi, [ui_i]
    imul edi, esi, 6
    lea edi, [ui_nodes + edi]
    movsx eax, word [edi + 0]      ; x
    movsx ebx, word [edi + 2]      ; y
    movsx ecx, word [edi + 4]      ; z

    ; x1 = (x*cosY - z*sinY) >> 8
    mov edx, eax
    imul edx, [ui_cosy]
    mov ebp, ecx
    imul ebp, [ui_siny]
    sub edx, ebp
    sar edx, 8
    mov [ui_tmp_x], edx

    ; z1 = (x*sinY + z*cosY) >> 8
    imul eax, [ui_siny]
    imul ecx, [ui_cosy]
    add eax, ecx
    sar eax, 8
    mov [ui_tmp_z], eax

    ; y2 = (y*cosP - z1*sinP) >> 8
    imul ebx, [ui_cosp]
    mov edx, eax
    imul edx, [ui_sinp]
    sub ebx, edx
    sar ebx, 8
    mov [ui_tmp_y], ebx

    ; depth = (y*sinP + z1*cosP) >> 8 + zoom
    movsx ebx, word [edi + 2]      ; original y
    imul ebx, [ui_sinp]
    mov edx, [ui_tmp_z]
    imul edx, [ui_cosp]
    add ebx, edx
    sar ebx, 8
    add ebx, [ui_zoom_q8]
    mov [ui_depth], ebx

    test ebx, ebx
    jle .cull
    cmp ebx, 2560                  ; closer than 10 px: clip
    jl .cull

    ; sx = 160 + x1 * FOV / depth (offset clamped to bound line lengths)
    mov eax, [ui_tmp_x]
    imul eax, UI_FOV
    cdq
    idiv dword [ui_depth]
    cmp eax, -1200
    jge .sx_min_ok
    mov eax, -1200
.sx_min_ok:
    cmp eax, 1200
    jle .sx_max_ok
    mov eax, 1200
.sx_max_ok:
    add eax, UI_CX
    mov [ui_sx + esi * 2], ax

    ; sy = 100 + y2 * FOV / depth
    mov eax, [ui_tmp_y]
    imul eax, UI_FOV
    cdq
    idiv dword [ui_depth]
    cmp eax, -1200
    jge .sy_min_ok
    mov eax, -1200
.sy_min_ok:
    cmp eax, 1200
    jle .sy_max_ok
    mov eax, 1200
.sy_max_ok:
    add eax, UI_CY
    mov [ui_sy + esi * 2], ax

    mov eax, [ui_depth]
    mov [ui_sz + esi * 4], eax
    mov byte [ui_on + esi], 1
    jmp .next
.cull:
    mov byte [ui_on + esi], 0
    mov dword [ui_sz + esi * 4], 0
.next:
    inc dword [ui_i]
    cmp dword [ui_i], UI_NODES
    jb .node
    popad
    ret

; =============================================================================
;  Depth sort: painter's algorithm, far to near (insertion sort, n=24)
; =============================================================================
ui_sort_nodes:
    pushad
    xor ecx, ecx
.init:
    mov [ui_order + ecx], cl
    inc ecx
    cmp ecx, UI_NODES
    jb .init

    mov ecx, 1
.outer:
    movzx ebp, byte [ui_order + ecx]
    mov edx, [ui_sz + ebp * 4]
    mov ebx, ecx
.inner:
    test ebx, ebx
    jz .place
    movzx esi, byte [ui_order + ebx - 1]
    mov edi, [ui_sz + esi * 4]
    cmp edi, edx
    jae .place
    mov eax, esi
    mov [ui_order + ebx], al
    dec ebx
    jmp .inner
.place:
    mov eax, ebp
    mov [ui_order + ebx], al
    inc ecx
    cmp ecx, UI_NODES
    jb .outer
    popad
    ret

; =============================================================================
;  Background: dithered CRT texture + starfield + perspective floor grid
; =============================================================================
ui_draw_background:
    mov eax, RAMP_BG + 1
    mov edx, RAMP_BG + 3
    call vga_clear_dither
    ret

ui_draw_stars:
    pushad
    xor ebp, ebp
.loop:
    movzx eax, byte [ui_star_x + ebp]
    movzx ebx, byte [ui_star_y + ebp]
    movzx edx, byte [ui_star_phase + ebp]
    mov esi, [pit_ticks]
    shr esi, 3
    add edx, esi
    and edx, 7
    add edx, RAMP_UI + 1
    mov ecx, edx
    call vga_putpixel
    inc ebp
    cmp ebp, UI_STARS
    jb .loop
    popad
    ret

ui_draw_grid:
    pushad
    ; horizontal perspective lines
    mov dword [ui_k], 0
.h_loop:
    mov eax, [ui_k]
    imul eax, eax, 8
    add eax, 126
    cmp eax, 168
    jae .h_done
    mov edx, [ui_k]
    add edx, RAMP_GRID + 3
    mov ebx, eax                   ; y
    xor eax, eax                   ; x
    mov ecx, VGA_WIDTH
    call vga_hline
    inc dword [ui_k]
    jmp .h_loop
.h_done:
    ; radial lines from the vanishing point to the bottom edge
    mov dword [ui_k], 0
.r_loop:
    mov eax, [ui_k]
    imul eax, eax, 40
    mov ecx, eax                   ; x1
    cmp ecx, VGA_WIDTH
    jae .r_done
    mov eax, UI_CX
    mov ebx, 112
    mov edx, 172
    mov esi, RAMP_GRID + 5
    add esi, [ui_k]
    call vga_line
    inc dword [ui_k]
    jmp .r_loop
.r_done:
    ; horizon glow
    xor eax, eax
    mov ebx, 112
    mov ecx, VGA_WIDTH
    mov edx, RAMP_GRID + 9
    call vga_hline
    popad
    ret

; =============================================================================
;  Synapse edges (two passes: soft glow + bright core)
; =============================================================================
ui_draw_edges:
    pushad
    mov dword [ui_i], 0
.edge:
    mov esi, [ui_i]
    movzx ecx, byte [ui_edges + esi * 2 + 0]
    movzx edx, byte [ui_edges + esi * 2 + 1]
    cmp byte [ui_on + ecx], 0
    je .next
    cmp byte [ui_on + edx], 0
    je .next

    ; coarse off-screen reject
    movsx eax, word [ui_sx + ecx * 2]
    movsx ebx, word [ui_sy + ecx * 2]
    movsx edi, word [ui_sx + edx * 2]
    movsx ebp, word [ui_sy + edx * 2]
    cmp eax, -40
    jge .a1
    cmp edi, -40
    jl .next
.a1:
    cmp eax, VGA_WIDTH + 40
    jle .a2
    cmp edi, VGA_WIDTH + 40
    jg .next
.a2:
    cmp ebx, -40
    jge .a3
    cmp ebp, -40
    jl .next
.a3:
    cmp ebx, VGA_HEIGHT + 40
    jle .a4
    cmp ebp, VGA_HEIGHT + 40
    jg .next
.a4:
    mov [ui_p0x], eax
    mov [ui_p0y], ebx
    mov [ui_p1x], edi
    mov [ui_p1y], ebp

    ; shade from average depth
    mov eax, [ui_sz + ecx * 4]
    add eax, [ui_sz + edx * 4]
    shr eax, 1
    call ui_depth_shade
    add eax, RAMP_EDGE + 1
    cmp eax, RAMP_EDGE + 31
    jbe .edge_color_ok
    mov eax, RAMP_EDGE + 31
.edge_color_ok:
    mov [ui_line_color], eax

    ; glow pass (offset one pixel down, darker)
    sub eax, 8
    cmp eax, RAMP_EDGE
    jae .glow_ok
    mov eax, RAMP_EDGE
.glow_ok:
    mov esi, eax
    mov eax, [ui_p0x]
    mov ebx, [ui_p0y]
    inc ebx
    mov ecx, [ui_p1x]
    mov edx, [ui_p1y]
    inc edx
    call vga_line

    ; core pass
    mov eax, [ui_p0x]
    mov ebx, [ui_p0y]
    mov ecx, [ui_p1x]
    mov edx, [ui_p1y]
    mov esi, [ui_line_color]
    call vga_line
.next:
    inc dword [ui_i]
    cmp dword [ui_i], UI_EDGES
    jb .edge
    popad
    ret

; =============================================================================
;  Travelling data packets
; =============================================================================
ui_draw_packets:
    pushad
    mov dword [ui_k], 0
.packet:
    ; edge index = (k*7 + tick>>5) % 40
    mov eax, [pit_ticks]
    shr eax, 5
    mov ecx, [ui_k]
    imul ecx, ecx, 7
    add eax, ecx
    xor edx, edx
    mov ecx, UI_EDGES
    div ecx
    mov esi, edx

    movzx eax, byte [ui_edges + esi * 2 + 0]
    movzx ecx, byte [ui_edges + esi * 2 + 1]
    cmp byte [ui_on + eax], 0
    je .next
    cmp byte [ui_on + ecx], 0
    je .next

    ; interpolation factor
    mov eax, [pit_ticks]
    imul eax, 3
    mov edx, [ui_k]
    imul edx, edx, 29
    add eax, edx
    and eax, 255
    mov [ui_t], eax

    ; endpoints
    movzx eax, byte [ui_edges + esi * 2 + 0]
    movsx edx, word [ui_sx + eax * 2]
    mov [ui_p0x], edx
    movsx edx, word [ui_sy + eax * 2]
    mov [ui_p0y], edx
    movzx eax, byte [ui_edges + esi * 2 + 1]
    movsx edx, word [ui_sx + eax * 2]
    mov [ui_p1x], edx
    movsx edx, word [ui_sy + eax * 2]
    mov [ui_p1y], edx

    ; x = x0 + ((x1-x0)*t) >> 8
    mov eax, [ui_p1x]
    sub eax, [ui_p0x]
    imul eax, [ui_t]
    sar eax, 8
    add eax, [ui_p0x]
    mov [ui_px], eax
    mov eax, [ui_p1y]
    sub eax, [ui_p0y]
    imul eax, [ui_t]
    sar eax, 8
    add eax, [ui_p0y]
    mov [ui_py], eax

    ; bright 3x3 dot with a tick-pulsed colour
    mov eax, [pit_ticks]
    shr eax, 2
    and eax, 3
    add eax, RAMP_NODE + 28
    mov esi, eax
    mov eax, [ui_px]
    sub eax, 1
    mov ebx, [ui_py]
    sub ebx, 1
    mov ecx, 3
    mov edx, 3
    call vga_fill_rect
.next:
    inc dword [ui_k]
    cmp dword [ui_k], UI_PACKETS
    jb .packet
    popad
    ret

; =============================================================================
;  Neurons
; =============================================================================
ui_draw_nodes:
    pushad
    mov dword [ui_i], 0
.node:
    mov esi, [ui_i]
    movzx eax, byte [ui_order + esi]
    mov [ui_idx], eax
    cmp byte [ui_on + eax], 0
    je .next
    mov esi, eax

    ; depth shade
    mov eax, [ui_sz + esi * 4]
    call ui_depth_shade
    mov [ui_shade], eax

    ; activation drives radius and colour
    movzx ebx, byte [snn_activation + esi]
    mov [ui_act], ebx

    ; projected centre
    movsx eax, word [ui_sx + esi * 2]
    mov [ui_px], eax
    movsx eax, word [ui_sy + esi * 2]
    mov [ui_py], eax

    ; radius = 3 + act/32 + shade/8, clamped to 9
    mov ecx, [ui_act]
    shr ecx, 5
    add ecx, 3
    mov edx, [ui_shade]
    shr edx, 3
    add ecx, edx
    cmp ecx, 9
    jbe .r_ok
    mov ecx, 9
.r_ok:
    mov [ui_r], ecx

    ; outer halo colour = node ramp + shade/3 + act/32
    mov edx, [ui_shade]
    shr edx, 3
    add edx, RAMP_NODE + 3
    mov ecx, [ui_act]
    shr ecx, 5
    add edx, ecx
    cmp edx, RAMP_NODE + 15
    jbe .oc_ok
    mov edx, RAMP_NODE + 15
.oc_ok:
    mov [ui_color], edx

    ; outer halo (+2 px)
    mov eax, [ui_px]
    mov ebx, [ui_py]
    mov ecx, [ui_r]
    add ecx, 2
    mov edx, [ui_color]
    call ui_draw_glow

    ; spike ring (if this neuron fired)
    mov esi, [ui_idx]
    cmp byte [snn_spiked + esi], 0
    je .no_spike
    mov eax, [ui_px]
    mov ebx, [ui_py]
    mov ecx, [ui_r]
    add ecx, 3
    mov edx, RAMP_NODE + 29
    call ui_draw_glow
.no_spike:

    ; inner core
    mov esi, [ui_idx]
    mov edx, [ui_shade]
    shr edx, 2
    add edx, RAMP_NODE + 14
    mov ecx, [ui_act]
    shr ecx, 5
    add edx, ecx
    cmp edx, RAMP_NODE + 30
    jbe .ic_ok
    mov edx, RAMP_NODE + 30
.ic_ok:
    mov eax, [ui_px]
    mov ebx, [ui_py]
    mov ecx, [ui_r]
    call ui_draw_glow

    ; white-hot centre only when the neuron actually spiked
    mov esi, [ui_idx]
    cmp byte [snn_spiked + esi], 0
    je .next
    mov eax, [ui_px]
    mov ebx, [ui_py]
    mov ecx, 2
    mov edx, COL_WHITE2
    call ui_draw_glow
.next:
    inc dword [ui_i]
    cmp dword [ui_i], UI_NODES
    jb .node
    popad
    ret

; -----------------------------------------------------------------------------
; ui_draw_glow: EAX=cx, EBX=cy, ECX=radius, EDX=colour. Filled circle, clipped.
; -----------------------------------------------------------------------------
ui_draw_glow:
    test ecx, ecx
    jle .done
    cmp ecx, 20
    jbe .r_ok
    mov ecx, 20
.r_ok:
    mov [glow_cx], eax
    mov [glow_cy], ebx
    mov [glow_r], ecx
    mov [glow_color], edx
    imul ecx, ecx
    mov [glow_r2], ecx

    mov eax, [glow_r]
    neg eax
    mov [glow_dy], eax
.dy:
    mov eax, [glow_dy]
    cmp eax, [glow_r]
    jg .done
    mov eax, [glow_r]
    neg eax
    mov [glow_dx], eax
.dx:
    mov eax, [glow_dx]
    cmp eax, [glow_r]
    jg .next_dy
    mov eax, [glow_dx]
    imul eax, eax
    mov ebx, [glow_dy]
    imul ebx, ebx
    add eax, ebx
    cmp eax, [glow_r2]
    ja .next_dx
    mov eax, [glow_cx]
    add eax, [glow_dx]
    mov ebx, [glow_cy]
    add ebx, [glow_dy]
    cmp eax, VGA_WIDTH
    jae .next_dx
    cmp ebx, VGA_HEIGHT
    jae .next_dx
    imul edi, ebx, VGA_WIDTH
    add edi, eax
    add edi, VGA_BACKBUF
    mov al, [glow_color]
    mov [edi], al
.next_dx:
    inc dword [glow_dx]
    jmp .dx
.next_dy:
    inc dword [glow_dy]
    jmp .dy
.done:
    ret

; -----------------------------------------------------------------------------
; ui_depth_shade: EAX = depth Q8.8 -> EAX = 0..31 (near = bright)
; -----------------------------------------------------------------------------
ui_depth_shade:
    sar eax, 8
    sub eax, 60
    jns .positive
    xor eax, eax
.positive:
    cmp eax, 340
    jbe .clamped
    mov eax, 340
.clamped:
    imul eax, 31
    xor edx, edx
    mov ecx, 340
    div ecx
    mov ecx, 31
    sub ecx, eax
    mov eax, ecx
    ret

; =============================================================================
