#!/usr/bin/env node
// Convert src/ui/font.asm (legacy 5x7 font data) -> src/ui/font.c (C table).
// Kept in tools/ for provenance; run manually after editing the legacy data.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const src = fs.readFileSync(path.join(ROOT, 'src', 'ui', 'font.asm'), 'utf8');

const rows = [];
const re = /^\s*db\s+([0-9a-fA-FxX, ]+)\s*;.*\((\d+)\)/gm;
let m;
while ((m = re.exec(src)) !== null) {
  const nums = m[1].match(/0x[0-9a-fA-F]+/g).map((s) => parseInt(s, 16));
  const ch = parseInt(m[2], 10);
  if (ch < 32 || ch > 126 || nums.length !== 5) {
    console.error(`bad glyph line: ch=${ch} nums=${nums}`);
    process.exit(1);
  }
  rows[ch - 32] = nums;
}
if (rows.length !== 95 || rows.some((r) => !r)) {
  console.error(`expected 95 glyphs, got ${rows.length}`);
  process.exit(1);
}

const lines = [];
lines.push('/*');
lines.push(' * ZenithOS v6.0 - 5x7 bitmap font (printable ASCII 32..126).');
lines.push(' * DO NOT EDIT: generated by tools/gen_font.mjs from the canonical');
lines.push(' * 5x7 dataset. Storage: 5 column bytes per glyph, left to right,');
lines.push(' * bit 0 = top row, bit 6 = bottom row.');
lines.push(' */');
lines.push('#include "font.h"');
lines.push('');
lines.push('static const uint8_t font_5x7[95][FONT_WIDTH] = {');
for (let i = 0; i < 95; i++) {
  const r = rows[i];
  lines.push('    { ' + r.map((v) => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ' }, /* ' + String.fromCharCode(i + 32) + ' */');
}
lines.push('};');
lines.push('');
lines.push('const uint8_t *font_glyph(char c) {');
lines.push('    unsigned char u = (unsigned char)c;');
lines.push('    if (u < FONT_FIRST || u > FONT_LAST) u = (unsigned char)\' \';');
lines.push('    return font_5x7[u - FONT_FIRST];');
lines.push('}');
lines.push('');

fs.writeFileSync(path.join(ROOT, 'src', 'ui', 'font.c'), lines.join('\n'));
console.log('wrote src/ui/font.c (' + (95 * 5) + ' bytes of glyph data)');
